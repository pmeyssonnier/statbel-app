// Drapeau depuis un code ISO2 (regional indicators). Vide si code invalide.
// NB : ne s'affiche pas sur Windows (→ 2 lettres) ; OK sur iOS/Android/Mac.
function flagFromIso2(iso2) {
  if (!iso2 || !/^[A-Za-z]{2}$/.test(iso2)) return '';
  return String.fromCodePoint(...[...iso2.toUpperCase()].map(c => 0x1F1E6 + c.charCodeAt(0) - 65));
}
function flagEmoji(iso3) { return flagFromIso2((PAYS_I18N[iso3] || {}).iso2 || ''); }
// « Drapeau + nom » (HTML échappé) pour une valeur pays (code ISO3 ou 'BEL').
function paysDrapeau(iso3) {
  const f = flagEmoji(iso3);
  return (f ? '<span style="margin-right:4px">' + f + '</span>' : '') + escHtml(paysNom(iso3) || iso3 || '—');
}
